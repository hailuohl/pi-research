"""Real Chromium tests against a running local server; no fake Agent or mocked API."""
import os, json, time, re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
BASE = os.environ.get('PI_TEST_URL', 'http://127.0.0.1:4317')
TOKEN = Path(os.environ.get('PI_TEST_DATA', str(Path(__file__).resolve().parents[2] / '.pi-research')), 'access.token').read_text().strip()
OUT = Path(os.environ.get('PI_TEST_OUTPUT', 'test-results/browser'))
OUT.mkdir(parents=True, exist_ok=True)
with sync_playwright() as pw:
    launch_options = {'headless': True}
    if os.environ.get('PI_CHROMIUM_EXECUTABLE'):
        launch_options['executable_path'] = os.environ['PI_CHROMIUM_EXECUTABLE']
    browser = pw.chromium.launch(**launch_options)
    page = browser.new_page(viewport={'width': 1440, 'height': 1000}, device_scale_factor=1)
    errors=[]
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(BASE+'/#token='+TOKEN)
    expect(page.get_by_role('button', name='新建项目', exact=True)).to_be_visible()
    page.get_by_role('button', name='新建项目', exact=True).click()
    page.get_by_label('项目名称').fill('曲线拟合 · 工作流验证')
    page.get_by_label('项目模板').select_option('curve-fit')
    page.get_by_role('button', name='创建项目', exact=True).click()
    expect(page.get_by_label('当前项目')).to_contain_text('曲线拟合 · 工作流验证')
    page.get_by_role('button', name='实验与运行', exact=True).click()
    page.get_by_role('button', name='新建实验', exact=True).click()
    page.get_by_label('实验名称').fill('基线 · 一阶模型')
    page.get_by_label('研究假设').fill('验证固定协议下的真实拟合指标。')
    page.get_by_role('button', name='保存实验草案', exact=True).click()
    expect(page.get_by_text('基线 · 一阶模型', exact=True).first).to_be_visible()
    page.get_by_role('button', name='准备运行', exact=True).click()
    expect(page.get_by_role('button', name='批准并提交', exact=True)).to_be_visible()
    page.get_by_role('button', name='批准并提交', exact=True).click()
    expect(page.get_by_test_id('selected-experiment-state')).to_contain_text('已冻结', timeout=20000)
    page.get_by_role('button', name='派生子实验', exact=True).click()
    page.get_by_label('实验名称').fill('候选 A · 二阶模型')
    page.get_by_label('研究假设').fill('与同一基线比较二阶模型。')
    page.get_by_label('版本化配置 JSON').fill('{"polynomialDegree":2,"ridge":0.000001}')
    page.get_by_role('button', name='保存实验草案', exact=True).click()
    page.get_by_role('button', name='准备运行', exact=True).click()
    page.get_by_role('button', name='批准并提交', exact=True).click()
    expect(page.get_by_test_id('selected-experiment-state')).to_contain_text('已冻结', timeout=20000)
    page.screenshot(path=str(OUT/'experiments-desktop.png'), full_page=True)
    page.get_by_role('button', name='报告与成果', exact=True).click()
    page.get_by_role('button', name='生成结果报告', exact=True).click()
    expect(page.get_by_text('生成时间：', exact=False).first).to_be_visible(timeout=10000)
    page.get_by_role('button', name='研究会话', exact=True).click()
    page.get_by_role('switch', name='多智能体协作').click()
    expect(page.get_by_role('switch', name='多智能体协作')).to_have_attribute('aria-checked','true')
    page.get_by_role('button', name='创建协作计划', exact=True).click()
    page.get_by_label('协作目标').fill('核查两次真实运行并独立审查')
    page.get_by_role('button', name='提交计划待批准', exact=True).click()
    expect(page.get_by_role('button', name='批准并启动协作', exact=True)).to_be_visible()
    page.get_by_role('button', name='批准并启动协作', exact=True).click()
    expect(page.get_by_text('尚未启动助手', exact=False).first).to_be_visible()
    page.screenshot(path=str(OUT/'collaboration-desktop.png'), full_page=True)
    page.reload()
    expect(page.get_by_role('switch', name='多智能体协作')).to_have_attribute('aria-checked','true')
    page.get_by_role('switch', name='多智能体协作').click()
    expect(page.get_by_text('待人工处理', exact=True).first).to_be_visible()
    page.get_by_role('button', name='项目工作区', exact=True).click()
    page.get_by_role('button', name='config.json', exact=True).click()
    expect(page.get_by_label('文件内容')).to_have_value(re.compile('polynomialDegree'))
    page.get_by_label('文件内容').fill('{"polynomialDegree":3,"ridge":0.000001}')
    page.get_by_role('button', name='保存文件', exact=True).click()
    expect(page.get_by_text('文件已保存', exact=True)).to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    page.get_by_role('button', name='研究会话', exact=True).click()
    page.screenshot(path=str(OUT/'mobile.png'), full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'mobile overflow'
    assert not errors, errors
    browser.close()
    (OUT/'result.json').write_text(json.dumps({'passed':True,'browser':'Chromium','desktop':[1440,1000],'mobile':[390,844],'pageErrors':errors,'flow':'create → approved snapshot runs → report → team approval/drain → reload → file edit'},ensure_ascii=False,indent=2))
print('Workbench browser flow PASS')
